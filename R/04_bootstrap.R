# =============================================================================
# 04_bootstrap.R
# Step 4. Block wild bootstrap (Section 3) and direct and indirect effects
# under the regional median spatial coefficients (Section 4.5).
#
# Pseudo-data: y* = (I - diag(rho_t) W)^(-1) (fitted part + residual_t * xi_t),
# with Mammen two-point multipliers xi in twelve-month blocks, shared by all
# LADs. Dates, seasonal adjustment, covariates, factor proxies and W are held
# fixed; the CCEX-IV coefficients are re-estimated in each of 199 draws.
# The baseline summaries are regional medians. Their 95% intervals are
# "estimate +/- 1.96 x bootstrap SE", and the matrix S = (I - diag(rho) W)^(-1)
# of the effect decompositions is recomputed at the regional spatial medians
# of every draw.
# Feeds: Tables 5-10 (standard errors); Figures 4-6 (bands).
# =============================================================================

# -----------------------------------------------------------------------------
# mammen_multipliers()
#   What it does : `reps` sequences of Mammen two-point multipliers, constant
#                  within blocks of `block` months (fixed seed). One sequence
#                  per draw, shared by all LADs.
#   Called by    : run_all.R (Step 4); common_date_simulation() [06]
#   Feeds        : all bootstrap SEs and bands (Tables 5-10; Figures 4-6);
#                  the common-date simulation (Table 4; Figure 2)
# -----------------------------------------------------------------------------
mammen_multipliers <- function(reps, nt, block, seed) {
  set.seed(seed)
  values <- c((1 - sqrt(5)) / 2, (1 + sqrt(5)) / 2)
  probs <- c((sqrt(5) + 1) / (2 * sqrt(5)), (sqrt(5) - 1) / (2 * sqrt(5)))
  out <- list()
  for (b in 1:reps) {
    xi <- sample(values, ceiling(nt / block), replace = TRUE, prob = probs)
    out[[b]] <- rep(xi, each = block)[1:nt]
  }
  out
}

# -----------------------------------------------------------------------------
# spatial_noise()
#   What it does : For every month, (I - diag(rho_t) W)^(-1) residual_t, the part
#                  of y generated by the residuals through the fitted spatial
#                  system. Regimes without an estimate (rho NA) get rho = 0.
#   Called by    : bootstrap_local(); bootstrap_common(); weights_analysis() [05]
#   Feeds        : all bootstrap SEs and bands (Tables 5-10; Figures 4-6)
# -----------------------------------------------------------------------------
spatial_noise <- function(panel, W, fit) {
  noise <- matrix(NA, panel$T, panel$N)
  for (t in 1:panel$T) {
    rho_t <- fit$coef[t, , 1]
    rho_t[!is.finite(rho_t)] <- 0
    A <- diag(panel$N) - W * rho_t
    noise[t, ] <- solve(A, fit$residual[t, ])
  }
  noise
}

# -----------------------------------------------------------------------------
# boot_coefficients()
#   What it does : Re-estimates every regime's IV coefficients on pseudo data
#                  Ystar, reusing the instrument bases stored by fit_panel_iv().
#   Called by    : bootstrap_local(); bootstrap_common(); weights_analysis() [05]
#   Feeds        : all bootstrap SEs and bands (Tables 5-10; Figures 4-6)
# -----------------------------------------------------------------------------
boot_coefficients <- function(Ystar, panel, W, fit) {
  WYstar <- Ystar %*% t(W)
  out <- array(NA, c(panel$T, panel$N, 3))
  for (i in 1:panel$N) {
    for (f in fit$details[[i]]) {
      if (is.null(f$z_basis)) next            # regime not identified: stays NA
      rows <- f$rows
      C <- cbind(crossprod(f$z_basis, WYstar[rows, i]),
          crossprod(f$z_basis, panel$X[rows, i, ]))
      yy <- crossprod(f$z_basis, Ystar[rows, i])
      beta <- qr.coef(qr(C, tol = 1e-10), yy)
      for (k in 1:3) out[rows, i, k] <- beta[k]
    }
  }
  out
}

# -----------------------------------------------------------------------------
# regional_means()
#   What it does : Monthly equally weighted mean of each coefficient in each
#                  region (City of London left out). T x 5 x 3 array.
#   Called by    : bootstrap_local()
#   Feeds        : Table 5, Panel A (mean-group estimates)
# -----------------------------------------------------------------------------
regional_means <- function(theta, gi) {
  out <- array(NA, c(dim(theta)[1], 5, 3))
  for (g in 1:5) for (k in 1:3) out[, g, k] <- rowMeans(theta[, gi[[g]], k])
  out
}

# -----------------------------------------------------------------------------
# regional_medians()
#   What it does : Monthly median across LADs of each coefficient in each
#                  region (City of London left out). T x 5 x 3 array. Within a
#                  common regime every month has the same value, so the value
#                  in the first month of the regime is the regime median.
#   Called by    : bootstrap_local(); bootstrap_common()
#   Feeds        : Figure 4 (local and common lines); Table 7
# -----------------------------------------------------------------------------
regional_medians <- function(theta, gi) {
  out <- array(NA, c(dim(theta)[1], 5, 3))
  for (g in 1:5) for (k in 1:3) out[, g, k] <- apply(theta[, gi[[g]], k], 1, median)
  out
}

# -----------------------------------------------------------------------------
# region_medians_all()
#   What it does : Median of each coefficient over all LAD-months of each
#                  region (City of London left out), so a regime counts once
#                  for every month it covers. 5 x 3 matrix.
#   Called by    : bootstrap_local(); weights_analysis() [05]
#   Feeds        : Table 5, Panel B; Table 10; the spatial coefficients
#                  assigned to each LAD in Figures 5, 6 and Tables 8, 9
# -----------------------------------------------------------------------------
region_medians_all <- function(theta, gi) {
  out <- matrix(NA, 5, 3)
  for (g in 1:5) for (k in 1:3) out[g, k] <- median(theta[, gi[[g]], k])
  out
}

# -----------------------------------------------------------------------------
# normal_band()
#   What it does : 95% interval "estimate +/- 1.96 x bootstrap SE", where the
#                  SE is the standard deviation over the draws (first
#                  dimension of `draws`). Used for all median-based results.
#   Called by    : bootstrap_local(); bootstrap_common(); weights_analysis() [05]
#   Feeds        : bands of Figures 4-6
# -----------------------------------------------------------------------------
normal_band <- function(point, draws) {
  se <- apply(draws, 2:length(dim(draws)), sd)
  list(se = se, lower = point - 1.96 * se, upper = point + 1.96 * se)
}

# -----------------------------------------------------------------------------
# pooled_summary()
#   What it does : Mean, median, P25, P75, P10 and P90 of each coefficient over
#                  all LAD-months outside the City of London. 3 x 6 matrix.
#   Called by    : bootstrap_local()
#   Feeds        : Table 6
# -----------------------------------------------------------------------------
pooled_summary <- function(theta, units) {
  out <- matrix(NA, 3, 6)
  for (k in 1:3) {
    z <- as.numeric(theta[, units, k])
    out[k, ] <- c(mean(z), quantile(z, c(0.5, 0.25, 0.75, 0.1, 0.9), type = 7))
  }
  out
}

# -----------------------------------------------------------------------------
# fixed_operator()
#   What it does : S = (I - diag(rho) W)^(-1) with every LAD's rho set to its
#                  region's value (the regional spatial median); checks that
#                  the system is stable (spectral radius of diag(rho) W below
#                  one).
#   Called by    : bootstrap_local() and bootstrap_common() (point estimate
#                  and once in every draw); weights_analysis() [05]
#   Feeds        : Figures 5, 6; Tables 8, 9; spectral radius 0.961 in the
#                  footnote of Section 4.5
# -----------------------------------------------------------------------------
fixed_operator <- function(panel, W, rho_group) {
  rho <- rho_group[match(panel$units$group, panel$groups)]
  B <- W * rho
  S <- solve(diag(panel$N) - B)
  radius <- max(Mod(eigen(B, only.values = TRUE)$values))
  stopifnot(radius < 1, all(S >= -1e-12))
  list(rho_group = rho_group, S = S, spectral_radius = radius)
}

# -----------------------------------------------------------------------------
# response_paths()
#   What it does : For sales and employment, direct effects (diagonal of
#                  S diag(beta)), indirect effects (off-diagonal row sums) and
#                  total effects (row sums) of every LAD in every month; then
#                  the median over the LADs of each region. The total is the
#                  median of the LAD totals, so it need not equal the median
#                  direct plus the median indirect effect. The City of
#                  London is left out as a receiving LAD and as a source.
#                  Returns T x 5 x 2 x 3 [month, region, (sales, employment),
#                  (direct, indirect, total)].
#   Called by    : bootstrap_local(); bootstrap_common(); weights_analysis() [05]
#   Feeds        : Figures 5, 6; Tables 8, 9; Section 4.5 text
# -----------------------------------------------------------------------------
response_paths <- function(theta, panel, op) {
  gi <- summary_groups(panel)
  city <- which(panel$units$areacode == "E09000001")
  nt <- dim(theta)[1]
  out <- array(NA, c(nt, 5, 2, 3))
  for (k in 1:2) {
    beta <- matrix(theta[, , k + 1], nt, panel$N)   # sales (k = 1) or employment (k = 2)
    beta[, city] <- 0
    direct <- sweep(beta, 2, diag(op$S), "*")
    total <- beta %*% t(op$S)
    indirect <- total - direct
    for (g in 1:5) {
      out[, g, k, 1] <- apply(direct[, gi[[g]], drop = FALSE], 1, median)
      out[, g, k, 2] <- apply(indirect[, gi[[g]], drop = FALSE], 1, median)
      out[, g, k, 3] <- apply(total[, gi[[g]], drop = FALSE], 1, median)
    }
  }
  out
}

# -----------------------------------------------------------------------------
# bootstrap_local()
#   What it does : 199 bootstrap draws of the local-date fit. In each draw:
#                  regional monthly medians, regional medians over all
#                  LAD-months (Table 5, Panel B), regional mean-group
#                  estimates (Table 5, Panel A), the pooled distribution, and
#                  the effects under S recomputed at that draw's regional
#                  spatial medians. Intervals for median-based results are
#                  estimate +/- 1.96 SE.
#   Called by    : run_all.R (Step 4)
#   Feeds        : Table 5 (Panels A and B), Table 6, Table 10 (inverse-
#                  distance columns); Figure 4 (local lines); Figure 5
# -----------------------------------------------------------------------------
bootstrap_local <- function(panel, fit, xi) {
  reps <- length(xi)
  gi <- summary_groups(panel)
  units <- sort(unlist(gi))
  # Point estimates
  md_point <- regional_medians(fit$coef, gi)
  mg_point <- regional_means(fit$coef, gi)
  median_point <- region_medians_all(fit$coef, gi)
  pooled_point <- pooled_summary(fit$coef, units)
  op <- fixed_operator(panel, panel$W, median_point[, 1])
  resp_point <- response_paths(fit$coef, panel, op)
  # Bootstrap draws
  noise <- spatial_noise(panel, panel$W, fit)
  base <- panel$Y - noise
  md_draws <- array(NA, c(reps, panel$T, 5, 3))
  period_draws <- array(NA, c(reps, 5, 3))
  median_draws <- array(NA, c(reps, 5, 3))
  pooled_draws <- array(NA, c(reps, 3, 6))
  resp_draws <- array(NA, c(reps, panel$T, 5, 2, 3))
  for (b in 1:reps) {
    theta <- boot_coefficients(base + noise * xi[[b]], panel, panel$W, fit)
    md_draws[b, , , ] <- regional_medians(theta, gi)
    period_draws[b, , ] <- apply(regional_means(theta, gi), 2:3, mean)
    median_draws[b, , ] <- region_medians_all(theta, gi)
    pooled_draws[b, , ] <- pooled_summary(theta, units)
    op_b <- fixed_operator(panel, panel$W, median_draws[b, , 1])   # recalibrated
    resp_draws[b, , , , ] <- response_paths(theta, panel, op_b)
    if (b %% 20 == 0) cat("  Bootstrap, local dates:", b, "of", reps, "\n")
  }
  md_band <- normal_band(md_point, md_draws)
  resp_band <- normal_band(resp_point, resp_draws)
  period_mean <- apply(mg_point, 2:3, mean)
  period_se <- apply(period_draws, 2:3, sd)
  median_se <- apply(median_draws, 2:3, sd)
  pooled_se <- apply(pooled_draws, 2:3, sd)
  list(md_point = md_point, md_lower = md_band$lower, md_upper = md_band$upper,
      period_mean = period_mean, period_se = period_se,
      period_p = 2 * pnorm(-abs(period_mean / period_se)),
      median_point = median_point, median_se = median_se,
      median_p = 2 * pnorm(-abs(median_point / median_se)),
      rho_draws = median_draws[, , 1],
      pooled_point = pooled_point, pooled_se = pooled_se,
      pooled_p = 2 * pnorm(-abs(pooled_point / pooled_se)),
      op = op, resp_point = resp_point, resp_lower = resp_band$lower,
      resp_upper = resp_band$upper, resp_draws = resp_draws)
}

# -----------------------------------------------------------------------------
# bootstrap_common()
#   What it does : 199 bootstrap draws of the common-date fit (same
#                  multipliers). In each draw: regional monthly medians,
#                  regional medians within each common regime, and the direct,
#                  indirect and total effects within each common regime, with
#                  every LAD given its region's median spatial coefficient from
#                  the local-date fit (Table 5, Panel B); in draw b these
#                  medians come from local-date draw b.
#   Called by    : run_all.R (Step 4)
#   Feeds        : Figure 4 (common lines); Tables 7-9
# -----------------------------------------------------------------------------
bootstrap_common <- function(panel, fit, common_breaks, bl, xi) {
  reps <- length(xi)
  gi <- summary_groups(panel)
  starts <- c(1, common_breaks + 1)
  ends <- c(common_breaks, panel$T)
  n_reg <- length(starts)
  md_point <- regional_medians(fit$coef, gi)
  regime_point <- md_point[starts, , ]
  effect_point <- response_paths(fit$coef[starts, , , drop = FALSE], panel, bl$op)
  noise <- spatial_noise(panel, panel$W, fit)
  base <- panel$Y - noise
  md_draws <- array(NA, c(reps, panel$T, 5, 3))
  effect_draws <- array(NA, c(reps, n_reg, 5, 2, 3))
  for (b in 1:reps) {
    theta <- boot_coefficients(base + noise * xi[[b]], panel, panel$W, fit)
    md_draws[b, , , ] <- regional_medians(theta, gi)
    op_b <- fixed_operator(panel, panel$W, bl$rho_draws[b, ])       # recalibrated
    effect_draws[b, , , , ] <- response_paths(theta[starts, , , drop = FALSE], panel, op_b)
    if (b %% 20 == 0) cat("  Bootstrap, common dates:", b, "of", reps, "\n")
  }
  md_band <- normal_band(md_point, md_draws)
  regime_se <- md_band$se[starts, , ]
  effect_se <- apply(effect_draws, 2:5, sd)
  list(md_point = md_point, md_lower = md_band$lower, md_upper = md_band$upper,
      starts = starts, ends = ends,
      regime_point = regime_point, regime_se = regime_se,
      regime_p = 2 * pnorm(-abs(regime_point / regime_se)),
      effect_point = effect_point, effect_se = effect_se,
      effect_p = 2 * pnorm(-abs(effect_point / effect_se)))
}
